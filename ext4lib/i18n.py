def detect_language() -> str:
    """Pick ko/en/ja from the OS locale, falling back to Korean."""
    try:
        value = locale.getlocale()[0] or ""
    except Exception:
        value = ""
    prefix = value.lower().replace("-", "_").split("_", 1)[0]
    return prefix if prefix in LANGUAGES else "ko"


def _settings_path() -> Path:
    base = os.environ.get("LOCALAPPDATA")
    if base:
        return Path(base) / "Ext4Reader" / "settings.json"
    return Path.home() / ".ext4reader" / "settings.json"


def load_language() -> str:
    path = _settings_path()
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
        language = str(data.get("language", "")).lower()
        if language in LANGUAGES:
            return language
    except (OSError, ValueError, TypeError):
        pass
    return detect_language()


def save_language(language: str) -> None:
    if language not in LANGUAGES:
        raise ValueError(f"Unsupported language: {language}")
    path = _settings_path()
    path.parent.mkdir(parents=True, exist_ok=True)
    data = {}
    try:
        current = json.loads(path.read_text(encoding="utf-8"))
        if isinstance(current, dict):
            data.update(current)
    except (OSError, ValueError, TypeError):
        pass
    data["language"] = language
    temp = path.with_suffix(".tmp")
    temp.write_text(json.dumps(data, ensure_ascii=False, indent=2), encoding="utf-8")
    temp.replace(path)


def language_label(language: str) -> str:
    return LANGUAGES.get(language, LANGUAGES["ko"])


def language_from_label(label: str) -> str:
    for code, name in LANGUAGES.items():
        if label == name:
            return code
    return "ko"


def tr(language: str, key: str, **kwargs) -> str:
    table = _MESSAGES.get(language) or _MESSAGES["ko"]
    value = table.get(key) or _MESSAGES["ko"].get(key) or key
    if kwargs:
        try:
            return value.format(**kwargs)
        except (KeyError, ValueError):
            return value
    return value
