"""Generate ext4lib/fs/ucd_12_1.py from the Unicode 12.1.0 UCD.

The table mirrors Linux fs/unicode/mkutf8data.c for the 12.1.0 tree that
ext4 casefold (s_encoding = EXT4_ENC_UTF8_12_1) uses:

* canonical decompositions only (every <tag> compatibility form is skipped),
  applied recursively;
* CaseFolding.txt status C and F (not S or T), applied recursively together
  with the decompositions (nfdicf_decompose);
* Default_Ignorable_Code_Point maps to the empty string;
* code points newer than 12.1.0 (DerivedAge) are left alone;
* canonical combining classes from UnicodeData.txt for the reordering step.

Hangul syllables are decomposed algorithmically at run time, like the
kernel does, so they are not stored.

Usage (offline; download the four files from
https://www.unicode.org/Public/12.1.0/ucd/ first):

    python tools/gen_casefold_12_1.py UCD_DIR [OUT_PY]
"""

from __future__ import annotations

import os
import sys

VERSION = "12.1.0"
HANGUL_FIRST, HANGUL_LAST = 0xAC00, 0xD7A3


def _lines(path: str):
    with open(path, encoding="utf-8") as fp:
        first = fp.readline()
        if path.endswith(("CaseFolding.txt", "DerivedAge.txt", "DerivedCoreProperties.txt")):
            if f"-{VERSION}.txt" not in first:
                raise SystemExit(f"{path}: not Unicode {VERSION} ({first.strip()})")
        for line in [first, *fp]:
            line = line.split("#", 1)[0].strip()
            if line:
                yield line


def _range(field: str) -> range:
    a, _, b = field.strip().partition("..")
    return range(int(a, 16), int(b or a, 16) + 1)


def load(ucd: str):
    assigned: set[int] = set()
    for line in _lines(os.path.join(ucd, "DerivedAge.txt")):
        cps, age = (f.strip() for f in line.split(";")[:2])
        if tuple(map(int, age.split("."))) <= (12, 1):
            assigned.update(_range(cps))

    ccc: dict[int, int] = {}
    decomp: dict[int, list[int]] = {}
    for line in _lines(os.path.join(ucd, "UnicodeData.txt")):
        f = line.split(";")
        cp = int(f[0], 16)
        if int(f[3]):
            ccc[cp] = int(f[3])
        if f[5] and not f[5].startswith("<"):
            decomp[cp] = [int(x, 16) for x in f[5].split()]

    fold: dict[int, list[int]] = {}
    for line in _lines(os.path.join(ucd, "CaseFolding.txt")):
        code, status, mapping = (f.strip() for f in line.split(";")[:3])
        if status in ("C", "F"):
            fold[int(code, 16)] = [int(x, 16) for x in mapping.split()]

    ignorable: set[int] = set()
    for line in _lines(os.path.join(ucd, "DerivedCoreProperties.txt")):
        cps, prop = (f.strip() for f in line.split(";")[:2])
        if prop == "Default_Ignorable_Code_Point":
            ignorable.update(_range(cps))

    for table in (ccc, decomp, fold):
        for cp in [cp for cp in table if cp not in assigned]:
            del table[cp]
    return ccc, decomp, fold, ignorable


def build(decomp, fold, ignorable) -> dict[int, list[int]]:
    memo: dict[int, list[int]] = {}

    def nfdicf(cp: int) -> list[int]:
        if cp in memo:
            return memo[cp]
        if cp in ignorable:
            out: list[int] = []
        elif cp in fold or cp in decomp:
            out = [y for x in (fold.get(cp) or decomp[cp]) for y in nfdicf(x)]
        else:
            out = [cp]
        memo[cp] = out
        return out

    table = {}
    for cp in sorted(set(fold) | set(decomp)):
        if HANGUL_FIRST <= cp <= HANGUL_LAST or cp in ignorable:
            continue
        out = nfdicf(cp)
        if out != [cp]:
            table[cp] = out
    return table


def _ranges(cps: set[int]) -> list[tuple[int, int]]:
    out: list[list[int]] = []
    for cp in sorted(cps):
        if out and out[-1][1] + 1 == cp:
            out[-1][1] = cp
        else:
            out.append([cp, cp])
    return [tuple(r) for r in out]


def _lit(cps: list[int]) -> str:
    return '"' + "".join(
        f"\\u{c:04x}" if c <= 0xFFFF else f"\\U{c:08x}" for c in cps
    ) + '"'


def emit(ccc, table, ignorable) -> str:
    out = [
        '"""Unicode 12.1.0 data for Linux utf8 NFD + casefold (nfdicf).',
        "",
        "GENERATED by tools/gen_casefold_12_1.py from the 12.1.0 UCD. Do not edit.",
        '"""',
        "",
        f'UNICODE_VERSION = "{VERSION}"',
        "",
        "# Default_Ignorable_Code_Point ranges: removed from casefolded names.",
        "IGNORABLE = (",
    ]
    out += [f"    (0x{a:04X}, 0x{b:04X})," for a, b in _ranges(ignorable)]
    out += [")", "", "# Canonical_Combining_Class != 0.", "CCC = {"]
    row = []
    for cp in sorted(ccc):
        row.append(f"0x{cp:04X}: {ccc[cp]},")
        if len(row) == 6:
            out.append("    " + " ".join(row))
            row = []
    if row:
        out.append("    " + " ".join(row))
    out += ["}", "", "# Full casefold + canonical decomposition (Hangul excluded).", "NFDICF = {"]
    out += [f"    0x{cp:04X}: {_lit(m)}," for cp, m in table.items()]
    out += ["}", ""]
    return "\n".join(out)


def main(argv: list[str]) -> int:
    if len(argv) not in (2, 3):
        print(__doc__)
        return 2
    ucd = argv[1]
    dest = argv[2] if len(argv) == 3 else os.path.join(
        os.path.dirname(__file__), "..", "ext4lib", "fs", "ucd_12_1.py"
    )
    ccc, decomp, fold, ignorable = load(ucd)
    table = build(decomp, fold, ignorable)
    with open(dest, "w", encoding="utf-8", newline="\n") as fp:
        fp.write(emit(ccc, table, ignorable))
    print(f"{dest}: {len(table)} mappings, {len(ccc)} ccc, {len(ignorable)} ignorable")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
